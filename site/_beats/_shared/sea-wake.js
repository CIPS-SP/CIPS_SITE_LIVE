/* _beats/_shared/sea-wake.js — the real-time teal sea + GPGPU wave-equation wake.
   Technique after unitedcarriers.com (see _assets/animation/cips-animation/reference/unitedcarriers/).
   29 Sep 2026, Simon: extracted out of seaway-wake/beat.js (unchanged — see that file's own history for how
   these numbers were tuned) so a new beat (noirmont-transit) can share the identical sea/wake, not a lesser
   copy. seaway-wake/beat.js re-exports these same names at its own bottom, so game.js's existing
   `import ... from './beat.js'` needs no changes. Textures regenerated by seaway-wake/make_water_textures.py. */
import * as THREE from 'three';
import { GPUComputationRenderer } from 'three/addons/misc/GPUComputationRenderer.js';

let WAKE_RUN=1.8, WAKE_INTENSITY=0.6;   // set from a beat's own mount() via setWakeParams()

/* ───────────────────────────── 0. SHARED NOISE (Ashima simplex, as UC) ───────────────────────────── */
const SNOISE = /* glsl */`
vec4 permute(vec4 x){return mod(((x*34.0)+1.0)*x,289.0);}
vec4 taylorInvSqrt(vec4 r){return 1.79284291400159-0.85373472095314*r;}
float snoise(vec3 v){
  const vec2 C=vec2(1.0/6.0,1.0/3.0); const vec4 D=vec4(0.0,0.5,1.0,2.0);
  vec3 i=floor(v+dot(v,C.yyy)); vec3 x0=v-i+dot(i,C.xxx);
  vec3 g=step(x0.yzx,x0.xyz); vec3 l=1.0-g; vec3 i1=min(g.xyz,l.zxy); vec3 i2=max(g.xyz,l.zxy);
  vec3 x1=x0-i1+1.0*C.xxx; vec3 x2=x0-i2+2.0*C.xxx; vec3 x3=x0-1.+3.0*C.xxx;
  i=mod(i,289.0);
  vec4 p=permute(permute(permute(i.z+vec4(0.0,i1.z,i2.z,1.0))+i.y+vec4(0.0,i1.y,i2.y,1.0))+i.x+vec4(0.0,i1.x,i2.x,1.0));
  float n_=1.0/7.0; vec3 ns=n_*D.wyz-D.xzx;
  vec4 j=p-49.0*floor(p*ns.z*ns.z); vec4 x_=floor(j*ns.z); vec4 y_=floor(j-7.0*x_);
  vec4 x=x_*ns.x+ns.yyyy; vec4 y=y_*ns.x+ns.yyyy; vec4 h=1.0-abs(x)-abs(y);
  vec4 b0=vec4(x.xy,y.xy); vec4 b1=vec4(x.zw,y.zw);
  vec4 s0=floor(b0)*2.0+1.0; vec4 s1=floor(b1)*2.0+1.0; vec4 sh=-step(h,vec4(0.0));
  vec4 a0=b0.xzyw+s0.xzyw*sh.xxyy; vec4 a1=b1.xzyw+s1.xzyw*sh.zzww;
  vec3 p0=vec3(a0.xy,h.x); vec3 p1=vec3(a0.zw,h.y); vec3 p2=vec3(a1.xy,h.z); vec3 p3=vec3(a1.zw,h.w);
  vec4 norm=taylorInvSqrt(vec4(dot(p0,p0),dot(p1,p1),dot(p2,p2),dot(p3,p3)));
  p0*=norm.x;p1*=norm.y;p2*=norm.z;p3*=norm.w;
  vec4 m=max(0.6-vec4(dot(x0,x0),dot(x1,x1),dot(x2,x2),dot(x3,x3)),0.0); m=m*m;
  return 42.0*dot(m*m,vec4(dot(p0,x0),dot(p1,x1),dot(p2,x2),dot(p3,x3)));
}`;

/* ───────────────────────────── 1. WAKE SIMULATION (GPGPU) ─────────────────────────────
 * A BOUNDS×BOUNDS world-unit patch of water (60×60) stored in an RES×RES float texture.
 *   R = surface height, G = vertical velocity.
 * Every frame each texel:
 *   a) ADVECTS: reads its previous state from slightly UPSTREAM (toward the bow).  ← "water flows past the ship"
 *   b) integrates the 2-D wave equation (Laplacian) with damping                    ← ripples spread + die
 *   c) injects the HULL crest (side walls, tapered bow/stern, bow pushes hardest)  ← region 1
 *   d) injects PROPELLER churn at the stern                                        ← region 2
 *   e) fades to zero at the texture border.
 * Because only (c)/(d) add energy, and (a) only carries it stern-wards, water AHEAD of
 * the bow and OUTSIDE the spreading V is never touched. That is why "parts the ship
 * hasn't passed through" stay calm with zero extra logic.
 */
const WAKE_FRAG = /* glsl */`
#include <common>
uniform vec2  uShipPos;       // hull centre, UV space
uniform vec2  uShipSize;      // hull (width, length) in UV space
uniform float uWakeIntensity; // 0.4 nominal, bobbed up to ~0.43
uniform float uTime, uDelta, uShipSpeed, uSmoothing;
// 30 Sep 2026: uShipRot — radians, default 0. game.js never sets this (its own hull is fixed "pointing down
// -Y" in this sim forever, and it makes the wake LOOK like it follows a turning hull by rotating its own 3D
// CAMERA in lock-step instead — verified directly in game.js, not assumed). A scroll-driven beat that wants the
// hull to visibly turn on a real heading, WITHOUT rotating the camera (which would also spin real satellite
// coastline/reflections — Simon: "the coast should certainly not rotate with the vessel... the reflections and
// waves would rotate with it which is unrealistic"), instead rotates the LOCAL hull-crest/prop-wash pattern
// itself by this angle, right here in the sim, leaving the camera and the background sea pattern untouched. At
// 0 (the default) this is a no-op — cos(0)=1, sin(0)=0 — so game.js's own existing wake is bit-for-bit unchanged.
uniform float uShipRot;
// 30 Sep 2026, Simon, again, with a screenshot pinpointing it: a patch of wake stayed pointing in her OLD
// heading (a yellow arrow in his own annotation) while the rest had already followed her turn (the green
// arrow) — "happening throughout... more of an issue when we make bigger heading changes". Right: rotating the
// FLOW direction (the previous fix, below this comment until 30 Sep) only steers where NEW energy heads from
// here on; it never moves the energy that was already laid down under the OLD flow direction — that old patch
// just gets carried along the NEW direction from wherever it already was, translating, not rotating, so it
// keeps its old shape/orientation for as long as it takes to decay. uShipRotDelta (radians turned THIS frame
// since last, tracked in JS — see beat.js) fixes the actual gap: every frame, the READ position is first
// un-rotated around uShipPos by that same small delta, so the whole stored field is kept rotating in lock-step
// with her, not just new inflow. Default 0 (game.js never sets it) is a no-op, same guarantee as uShipRot.
uniform float uShipRotDelta;
${SNOISE}
void main(){
  vec2 uv=gl_FragCoord.xy/resolution.xy; vec2 texel=1.0/resolution.xy;
  float dt=min(uDelta,0.033);

  // rotate the READ position around uShipPos by -uShipRotDelta first, so content already stored under an OLDER
  // heading is re-read as if the whole field had turned WITH her; the advection below then runs in her own
  // fixed local frame (bow always "down -Y"), same as it always did, no separate flow-direction rotation needed.
  vec2 relToShip=uv-uShipPos;
  { float rc=cos(-uShipRotDelta), rs=sin(-uShipRotDelta); relToShip=vec2(relToShip.x*rc-relToShip.y*rs, relToShip.x*rs+relToShip.y*rc); }
  vec2 rotatedUV=uShipPos+relToShip;
  // (a) ADVECTION — ship points DOWN (-Y) in her own local frame; wake trails UP (+Y)
  float uvSpeed=(uShipSpeed/BOUNDS)*0.38;           // 0.38 = "majestic" slow-down fudge
  vec2 src=rotatedUV-vec2(0.0,uvSpeed*dt);
  vec4 st=texture2D(heightmap,src); float h=st.r, v=st.g;
  float hL=texture2D(heightmap,src+vec2(-texel.x,0.)).r, hR=texture2D(heightmap,src+vec2(texel.x,0.)).r;
  float hD=texture2D(heightmap,src+vec2(0.,-texel.y)).r, hU=texture2D(heightmap,src+vec2(0.,texel.y)).r;

  // (b) WAVE EQUATION — c² must stay < 0.5 for grid stability
  float lap=(hL+hR+hD+hU)-4.0*h;
  v+=lap*0.12; v*=pow(0.95,1.0/RUN); h*=pow(0.97,1.0/RUN); h+=v;   // RUN>1 = slower decay = longer wake

  // (c) HULL CREST — rel is already in her current local/body frame with NO further rotation needed: region (a)'s
  // uShipRotDelta correction above continuously re-registers the whole stored field to her current heading every
  // frame, so raw (uv-uShipPos) already tracks her turn automatically. 30 Sep 2026: this used to ALSO rotate rel
  // by the absolute uShipRot here — a leftover from before the uShipRotDelta correction existed, when the crest
  // needed its own explicit rotation because nothing else was tracking heading yet. Once uShipRotDelta was added,
  // this became a second, redundant rotation stacked on top of the one the field already gets "for free" via (a)
  // — writing the crest ~2x the turn angle away from the hull, worse on bigger turns, never decaying (freshly
  // wrong every single frame). Simon: "locked there throughout... more visible on bigger turns away from the
  // original heading" — exactly this signature, not a decay-rate issue.
  vec2 rel=(uv-uShipPos)*BOUNDS;
  float hW=uShipSize.x*0.5*BOUNDS, hL_=uShipSize.y*0.5*BOUNDS;
  vec2 world=(uv-0.5)*BOUNDS;
  float ambient=snoise(vec3(world.x*0.01*NOISE_SCALE,world.y*0.01*NOISE_SCALE,uTime*0.5))*0.15;
  if(rel.y>-hL_&&rel.y<hL_){
    float localHW=hW;
    if(rel.y<-hL_*0.4){ float t=(rel.y+hL_)/(hL_*0.6); localHW=hW*smoothstep(0.,1.,t); }       // bow taper
    else if(rel.y>hL_*0.7){ float t=(hL_-rel.y)/(hL_*0.3); localHW=hW*smoothstep(0.,1.,t); }  // stern taper
    float distToSide=abs(rel.x)-localHW;
    float peakOffset=hW*0.08;                       // crest sits just outside the hull
    float dFromPeak=distToSide-peakOffset;
    float influence=max(hW*0.18,texel.x*BOUNDS*0.55); // never thinner than ~half a texel
    if(abs(dFromPeak)<influence){
      float factor=smoothstep(influence,0.0,abs(dFromPeak));
      float speedFactor=clamp(uShipSpeed/35.0,0.2,1.5);
      float lon=smoothstep(-hL_,-hL_*0.4,rel.y);      // 0 at bow → 1 amidships
      float strength=mix(0.12,0.55,lon)*uWakeIntensity*speedFactor;   // NB bow-ward end weaker here,
      float hullNoise=snoise(vec3(world*1.6,uTime*0.4))*0.25+0.85;    // the bow *spike* is cut in the ocean shader
      float force=factor*strength*(hullNoise+max(0.0,ambient)*2.0);
      h=mix(h,force,0.45); v=0.0;                    // clamp the crest to the hull (no pulsing)
    }
  }
  // (d) PROPELLER WASH
  vec2 prop=vec2(0.0,hL_*0.9); float dProp=length(rel-prop); float pr=hW*0.8;
  if(dProp<pr){
    float pn=snoise(vec3(rel*8.0,uTime*1.2))*0.9-0.12;   // zero-mean churn, amplitude ×2, with a slight bias so the prop disc reads for a short run astern (UC: *0.15-0.85 = trench)   // UC: *0.15-0.85 → strongly negative = digs a TROUGH down the centreline (the dark band). Zero-mean = churn only
    v+=pn*uWakeIntensity*0.05*smoothstep(pr,pr*0.2,dProp);
  }
  // cross blur kills vertical grid lines on the narrow crest
  float sm=(h*4.0+hL+hR+hD+hU)/8.0; h=mix(h,sm,clamp(uSmoothing,0.,1.));
  // (e) border fade
  float e=0.05; float fade=smoothstep(0.,e,uv.x)*smoothstep(0.,e,1.-uv.x)*smoothstep(0.,e,uv.y)*smoothstep(0.,e,1.-uv.y);
  h*=fade; v*=fade; h=clamp(h,-2.,2.); v=clamp(v,-2.,2.);
  gl_FragColor=vec4(h,v,0.,1.);
}`;

function createWakeSimulation(renderer,{resolution=256,bounds=60,shipWidth,shipLength,shipSpeed=65,wakeIntensity=.4,noiseScale=1.1,smoothing=.55,frag=WAKE_FRAG,extraUniforms=null}){   // frag / extraUniforms: game.js passes a variant with splash impulses (16 Sep); a beat passes nothing
  const gpu=new GPUComputationRenderer(resolution,resolution,renderer);
  const tex=gpu.createTexture(); tex.image.data.fill(0);
  const variable=gpu.addVariable('heightmap',`#define BOUNDS ${bounds.toFixed(1)}\n#define NOISE_SCALE ${noiseScale.toFixed(1)}\n#define RUN ${WAKE_RUN.toFixed(2)}\n`+frag,tex);
  gpu.setVariableDependencies(variable,[variable]);
  const u=variable.material.uniforms;
  Object.assign(u,{uShipPos:{value:new THREE.Vector2(.5,.5)},uShipSize:{value:new THREE.Vector2(shipWidth,shipLength)},
    uWakeIntensity:{value:wakeIntensity},uTime:{value:0},uDelta:{value:1/60},uShipSpeed:{value:shipSpeed},uSmoothing:{value:smoothing},
    uShipRot:{value:0},uShipRotDelta:{value:0}});
  if(extraUniforms) Object.assign(u,extraUniforms);
  variable.wrapS=variable.wrapT=THREE.ClampToEdgeWrapping; variable.minFilter=variable.magFilter=THREE.LinearFilter;
  const err=gpu.init(); if(err) console.error('[Wake] GPGPU init',err);
  variable.renderTargets?.forEach(rt=>{rt.texture.minFilter=rt.texture.magFilter=THREE.LinearFilter;});
  return {
    update(shipWorldPos,dt,t){ u.uShipPos.value.set(.5+shipWorldPos.x/bounds,.5+shipWorldPos.z/bounds); u.uTime.value=t; u.uDelta.value=dt; gpu.compute(); },
    texture(){ return gpu.getCurrentRenderTarget(variable).texture; },
    uniforms:u, dispose(){gpu.dispose();}
  };
}

/* ───────────────────────────── 2. OCEAN MATERIAL ─────────────────────────────
 * MeshStandardMaterial (roughness 0, metalness .61, env-map) with three injected behaviours:
 *   VERTEX   : ambient swell (2 octaves simplex) + wake height; ambient swell DAMPED 85% inside a V channel.
 *   NORMALS  : two scrolling normal maps, their UVs "parted" sideways inside the V, + wake slope from the heightmap.
 *   COLOUR   : foam — (i) curvature foam on crests, (ii) analytical twin side-lines, (iii) central prop wash —
 *              gated to a trapezoid behind the hull; white → pale-blue with distance; foam sets roughness .97.
 * A procedural deep-blue gradient replaces UC's screen-space overlay photo + radial glows (kept out for clarity).
 */
const BOUNDS=60;
function makeOcean(wake,normalMap,envMap,resolution){
  const uni={
    uTime:{value:0},uHeightmap:{value:wake.texture()},uHeightScale:{value:1.7},uWakeOffsetY:{value:-0.5},
    uOceanSpeed:{value:.9},uFoamThreshold:{value:.83},uFoamIntensity:{value:.26},uWashFoam:{value:.75},
    uWakeIntensity:{value:WAKE_INTENSITY},uWakeFade:{value:1},uEdgeFade:{value:.25},
    /* JERSEY PALETTE — sampled from img/wake.jpg & sea.jpg (p10 #013f46 · p50 #02615f · p90 #127e79).
       UC: #193653 → #021436 (cobalt). Ours sits on the teal side of that wheel. */
    uTopColor:{value:new THREE.Color('#0d7a76')},uBottomColor:{value:new THREE.Color('#02484b')},
    uSunHighlightKnee:{value:.32},uSunHighlightCompression:{value:2.2},
    uCamHeight:{value:20},uFlow:{value:1.6},   // uFlow: world units/s the water streams astern past the (fixed) hull
    uPan:{value:new THREE.Vector2(0,0)},      // world-xz offset the sea PATTERN is shifted by — set to the camera's aim so the sea stays still on screen while the hull crosses it
    // 30 Sep 2026, Simon, with an annotated screenshot (yellow = where the wake actually pointed, green = where
    // it should have): the WAKE_FRAG heightmap sim itself was already rotating correctly by this point, but this
    // OCEAN MESH's own foam/calm-channel/gate rendering — a completely separate shader, never touched by that
    // fix — still tested `position.xy`/`vOceanWorldPosition.xz` directly, a frame that never rotates (the mesh
    // itself never turns; only its own per-vertex wake-relative math was meant to track her). So the VISIBLE
    // foam (the twin Kelvin arms, the gate that decides where foam can appear at all, the normal-map "part the
    // ripples" push) stayed locked to the original un-rotated axis regardless of the — correctly rotating —
    // heightmap underneath it. Same uShipRot this material's own sibling (the wake sim) already uses; default 0
    // is a no-op, so game.js (never sets it) is unaffected.
    uShipRot:{value:0}
  };
  /* UC uses metalness .61 / roughness 0 for a cobalt mirror. Real shallow teal water is a DIELECTRIC:
     colour comes from the body (absorption/scatter), reflections are Fresnel-only. So metalness 0,
     a little roughness to break the mirror into the fine glint field seen in the drone shot. */
  const mat=new THREE.MeshStandardMaterial({color:new THREE.Color('#0b6b68'),roughness:.13,metalness:0,envMap,envMapIntensity:.5,
    normalMap,normalScale:new THREE.Vector2(.7,.7)});
  mat.onBeforeCompile=(sh)=>{
    Object.assign(sh.uniforms,uni);
    const head=`#define BOUNDS ${BOUNDS.toFixed(1)}\n#define NOISE_SCALE 1.1\n#define WAKE_RESOLUTION ${resolution.toFixed(1)}\n#define WAKE_NORMAL_STRENGTH 2.5\n#define RUN ${WAKE_RUN.toFixed(2)}\n`;
    sh.vertexShader=head+`
      uniform float uTime,uHeightScale,uWakeOffsetY,uOceanSpeed,uFlow,uShipRot,uWakeFade; uniform vec2 uPan; uniform sampler2D uHeightmap;
      varying float vWakeHeight; varying vec2 vWakeUv; varying vec3 vOceanWorldPosition; varying vec2 vPosRot; ${SNOISE}
    `+sh.vertexShader.replace('#include <begin_vertex>',`
      #include <begin_vertex>
      vOceanWorldPosition=(modelMatrix*vec4(position,1.0)).xyz;
      // her real heading, applied to the LOCAL position before any wake-relative geometry below — the mesh
      // itself never rotates (see uShipRot's own comment above), so every test that means "ahead of/behind/
      // beside the hull" has to rotate here instead, or it stays locked to the original axis. Same rotation
      // convention as WAKE_FRAG's own rel; uShipRot=0 (game.js) reduces this to position.xy unchanged.
      float wrc=cos(uShipRot), wrs=sin(uShipRot);
      vec2 posRot=vec2(position.x*wrc-position.y*wrs, position.x*wrs+position.y*wrc);
      vec2 wakeUv=vec2(0.5+posRot.x/BOUNDS,0.5+(posRot.y-uWakeOffsetY)/BOUNDS);
      float wakeHeight=texture2D(uHeightmap,wakeUv).r*uHeightScale*uWakeFade;   // uWakeFade: 1 = under way, 0 = no wake at all (a beat sets it to 0 once she is alongside)
      float fx=position.x-uPan.x; float fy=position.y+uPan.y-uTime*uFlow;   // ambient swell: locked to the camera (uPan) + slow astern drift — the BACKGROUND sea texture, not the wake, deliberately NOT rotated
      float elevation=snoise(vec3(fx*0.01*NOISE_SCALE,fy*0.01*NOISE_SCALE,uTime*0.5*uOceanSpeed))*0.15
                     +snoise(vec3(fx*0.02*NOISE_SCALE,fy*0.02*NOISE_SCALE,uTime*1.0*uOceanSpeed))*0.05;
      vec2 pd=vec2(posRot.x,posRot.y-uWakeOffsetY); float depth=max(0.0,pd.y);
      // kill the narrow spike that would poke out in front of the bow
      float bowCut=(1.0-smoothstep(-5.5,-0.4,pd.y))*(1.0-smoothstep(0.4,1.05,abs(pd.x))); wakeHeight*=1.0-bowCut;
      // V-shaped calm channel: half-width 2.2 + 0.28/unit, gone after 24 units astern
      float halfW=2.2+depth*0.28;
      float damp=smoothstep(halfW,halfW*0.35,abs(pd.x))*smoothstep(24.0*RUN,0.0,depth)*smoothstep(-1.5,0.0,pd.y);
      damp*=smoothstep(0.,.08,wakeUv.x)*smoothstep(0.,.08,1.-wakeUv.x)*smoothstep(0.,.08,wakeUv.y)*smoothstep(0.,.08,1.-wakeUv.y); damp*=uWakeFade;
      elevation*=(1.0-damp*0.5);   // UC 0.85 — the flattened swell also shaded the channel darker
      transformed.z+=elevation+wakeHeight; vWakeHeight=wakeHeight; vWakeUv=wakeUv; vPosRot=posRot;`);
    sh.fragmentShader=head+`
      uniform sampler2D uHeightmap; uniform float uHeightScale,uWakeOffsetY,uOceanSpeed,uFoamThreshold,uFoamIntensity,uWashFoam,uWakeIntensity,uWakeFade,uEdgeFade,uTime,uSunHighlightKnee,uSunHighlightCompression,uCamHeight,uFlow; uniform vec2 uPan;
      uniform vec3 uTopColor,uBottomColor; varying float vWakeHeight; varying vec2 vWakeUv; varying vec3 vOceanWorldPosition; varying vec2 vPosRot;
      float foamFactor=0.0; float edgeAlpha=0.0; ${SNOISE}
    `+sh.fragmentShader
    .replace('#include <color_fragment>',`
      #include <color_fragment>
      float fluid=snoise(vec3((vOceanWorldPosition.xz-uPan)*0.01*NOISE_SCALE,uTime*0.5));
      vec3 baseColor=mix(uTopColor,uBottomColor,0.5+fluid*0.05);
      float vFoam=0.0;
      // FOAM GATE — a trapezoid: 0.15 ahead of centre, 0.4 behind, half-width .05 + .3/unit (UV units of the 60-unit patch)
      vec2 gate0=vec2(0.5,0.5+uWakeOffsetY/BOUNDS); float gd=vWakeUv.y-gate0.y;
      float gHalf=0.05+max(gd,0.0)*0.3;
      bool insideWake=gd>=-0.15&&gd<=min(0.4*RUN,0.75)&&abs(vWakeUv.x-gate0.x)<=gHalf;
      if(insideWake){
        vec2 cs=1.6/vec2(WAKE_RESOLUTION);   // 1.6 texels, not 1 — softens single-texel grain at close zoom, keeps the crest shape
        float hV=texture2D(uHeightmap,vWakeUv).x;
        float hL=texture2D(uHeightmap,vWakeUv+vec2(-cs.x,0.)).x,hR=texture2D(uHeightmap,vWakeUv+vec2(cs.x,0.)).x;
        float hU=texture2D(uHeightmap,vWakeUv+vec2(0.,cs.y)).x,hD=texture2D(uHeightmap,vWakeUv+vec2(0.,-cs.y)).x;
        float crest=max(0.0,-((hL+hR+hU+hD)-4.0*hV))*38.0;            // curvature → crests
        // foam rides on the water → streams astern at uFlow. Uses vPosRot (her real-heading-rotated position),
        // not vOceanWorldPosition — this noise pattern is the WAKE's own churn texture, so it has to turn with
        // her the same way the gate/kelvin-arm geometry above (vWakeUv, already rotated) does, or the foam's own
        // internal texture reads off-axis against the now-correctly-rotated shape it's filling.
        float fz=-vPosRot.y-uPan.y+uTime*uFlow; float fxw=vPosRot.x-uPan.x;
        vec2 fuv=vec2(fxw*2.4,fz*0.32);            // stretched along travel
        float n1=1.0-abs(snoise(vec3(fuv*1.5,uTime*0.25)));          // churn a little faster than UC (0.15 / 0.25)
        float n2=1.0-abs(snoise(vec3(fuv*3.5,uTime*0.4)));
        float n=n1*0.6+n2*0.4;
        vec2 fine=vec2(fxw*30.0,fz*2.0);
        float fineFoam=smoothstep(0.4,0.75,snoise(vec3(fine,uTime*0.7))*0.5+0.5);
        float distBehind=max(0.0,vWakeUv.y-0.6);
        float dyn=uFoamThreshold*clamp(1.0-distBehind*0.95/RUN,0.4,1.0);
        float eroded=dyn*(1.7-n*1.1);
        foamFactor=smoothstep(eroded,eroded+0.08,crest)*fineFoam*n*2.2*smoothstep(0.55*RUN,0.10,distBehind)*uFoamIntensity;
        // (ii) analytical twin side lines (Kelvin arms)
        vec2 p=(vWakeUv-gate0)*16.0; float depth=max(0.0,p.y);
        float widthFactor=0.70+depth*0.06; float normX=p.x/widthFactor;
        float vMask=exp(-pow(abs(normX)-0.45,2.0)*18.0);
        float fadeOut=smoothstep(12.0*RUN,0.0,depth)*smoothstep(-0.5,0.2,p.y);
        vec2 bu=p*5.8; bu.y-=uTime*uFlow*(16.0/60.0)*5.8*0.8; bu.y*=mix(1.0,0.15,smoothstep(3.0,12.0,depth));   // bubbles stream astern with the sea
        float fn=0.5*(1.0-abs(snoise(vec3(bu,uTime*0.036))))+0.25*(1.0-abs(snoise(vec3(bu*2.1,-uTime*0.36))))+0.125*(1.0-abs(snoise(vec3(bu*4.3,uTime*0.45))));
        float bubbles=smoothstep(0.55,0.85,fn)*mix(1.0,fineFoam*1.5,smoothstep(0.0,6.0,depth));
        float foamArea=smoothstep(0.55,0.9,fadeOut*0.7+n*0.5);
        float dissipation=mix(1.0,foamArea,smoothstep(1.5,9.0*RUN,depth));
        vFoam=vMask*bubbles*dissipation*fadeOut*smoothstep(-0.5,0.2,p.y)*smoothstep(-0.05,0.25,crest+hV*0.5);
        foamFactor=max(foamFactor,vFoam*uFoamIntensity*1.2);
        // (iii) central prop wash, widening astern
        if(distBehind>0.0){
          float wHalf=0.03+distBehind*0.15;
          float env=smoothstep(wHalf,wHalf*0.25,abs(vWakeUv.x-0.5));
          foamFactor=max(foamFactor,env*n*fineFoam*smoothstep(0.32*RUN,0.02,distBehind)*uWashFoam*0.4*uFoamIntensity);
        }
        float bowCut=(1.0-smoothstep(-1.5,-0.1,p.y))*(1.0-smoothstep(0.10,0.28,abs(p.x))); foamFactor*=1.0-bowCut; foamFactor*=uWakeFade; vFoam*=uWakeFade;
      }
      edgeAlpha=smoothstep(0.,uEdgeFade,vWakeUv.x)*smoothstep(0.,uEdgeFade,1.-vWakeUv.x)*smoothstep(0.,uEdgeFade,vWakeUv.y)*smoothstep(0.,uEdgeFade,1.-vWakeUv.y);
      vec2 pc=(vWakeUv-gate0)*16.0; float dc=max(0.0,pc.y);
      vec3 farFoam=mix(vec3(1.0),vec3(0.545,0.714,0.871),clamp(dc/(9.0*RUN),0.,1.));   // foam goes pale blue astern
      vec3 foamCol=mix(vec3(0.88,0.94,0.97),farFoam,clamp(vFoam*2.0,0.,1.));
      baseColor=mix(baseColor,foamCol,clamp(foamFactor*edgeAlpha,0.,1.));
      diffuseColor=vec4(baseColor,diffuseColor.a);`)
    .replace('#include <normal_fragment_maps>',`
      #ifdef USE_NORMALMAP_TANGENTSPACE
        // vPosRot again, not vOceanWorldPosition.xz — same reasoning as the foam noise above: this "part the
        // ripples sideways" push is wake-relative (either side of her hull), so it has to rotate with her real
        // heading, not stay locked to the mesh's own un-rotating local axis.
        vec2 wd=vec2(vPosRot.x,-vPosRot.y)-vec2(0.0,uWakeOffsetY); float depth=max(0.0,-wd.y);
        float wf=2.5+depth*0.25; float nx=wd.x/wf;
        float push=nx*exp(-nx*nx*2.0), pushY=exp(-nx*nx*2.0);
        float fo=smoothstep(60.0,0.0,depth)*smoothstep(-6.0,3.0,wd.y)*uWakeFade;
        float ps=2.2*uWakeIntensity;
        vec2 off=vec2(-push*ps*fo,-pushY*ps*0.5*fo)*0.002;                       // "part" the ripples sideways
        /* Anti-lattice: UC samples the map at 1× and 2× of the SAME uv, so the 68× tiling shows as a diamond grid when the
           glints fade. Here three layers are built in WORLD space with incommensurate scales (1 : 2.15 : 1/2.3) and
           rotations, so no two repeats line up; the fine layer fades out with altitude (it would alias anyway) and the
           broad layer fades in. All layers stream astern (+local y = −world z) at uFlow so the sea moves past the hull. */
        const float TILE=2000.0/68.0;                                   // 29.4 units per tile, as UC
        vec2 wp=vOceanWorldPosition.xz-uPan; wp.y+=uTime*uFlow;               // flow astern: astern = local +y = world −z, so ADD on z
        mat2 rA=mat2(cos(1.2),-sin(1.2),sin(1.2),cos(1.2));
        mat2 rB=mat2(cos(-0.8),-sin(-0.8),sin(-0.8),cos(-0.8));
        mat2 rC=mat2(cos(0.5),-sin(0.5),sin(0.5),cos(0.5));
        float fineW=smoothstep(80.0,15.0,uCamHeight);
        float broadW=0.35+0.65*smoothstep(15.0,60.0,uCamHeight);
        vec3 m1=texture2D(normalMap,rA*wp/TILE+vec2(uTime*0.004,0.0)+off).xyz*2.0-1.0; m1.xy*=normalScale;
        vec3 m2=texture2D(normalMap,rB*wp/(TILE*2.15)+vec2(0.0,uTime*0.002)+off*0.5).xyz*2.0-1.0; m2.xy*=normalScale*broadW*0.9;
        vec3 m3=texture2D(normalMap,rC*wp/(TILE/2.3)+vec2(-uTime*0.006,0.0)+off*2.0).xyz*2.0-1.0; m3.xy*=normalScale*fineW*0.6;
        vec3 on=vec3(m1.xy+m2.xy+m3.xy,1.0);
        vec2 pd=vec2(wd.x,-wd.y); float dd=max(0.0,pd.y); float hw=2.2+dd*0.28;
        float damp=smoothstep(hw,hw*0.35,abs(pd.x))*smoothstep(24.0*RUN,0.0,dd)*smoothstep(-1.5,0.0,pd.y);
        damp*=smoothstep(0.,.08,vWakeUv.x)*smoothstep(0.,.08,1.-vWakeUv.x)*smoothstep(0.,.08,vWakeUv.y)*smoothstep(0.,.08,1.-vWakeUv.y); damp*=uWakeFade;
        on.xy*=(1.0-damp*0.2);                                                   // UC 0.85 — fully flat water mirrors the dark zenith and reads as a shadow trailing aft
        vec2 ncs=3.2/vec2(WAKE_RESOLUTION);
        float nL=texture2D(uHeightmap,vWakeUv+vec2(-ncs.x,0.)).x,nR=texture2D(uHeightmap,vWakeUv+vec2(ncs.x,0.)).x;
        float nU=texture2D(uHeightmap,vWakeUv+vec2(0.,ncs.y)).x,nD=texture2D(uHeightmap,vWakeUv+vec2(0.,-ncs.y)).x;
        vec3 wn=vec3((nL-nR)*WAKE_NORMAL_STRENGTH*uHeightScale,(nD-nU)*WAKE_NORMAL_STRENGTH*uHeightScale,0.0);
        float nea=smoothstep(0.,uEdgeFade,vWakeUv.x)*smoothstep(0.,uEdgeFade,1.-vWakeUv.x)*smoothstep(0.,uEdgeFade,vWakeUv.y)*smoothstep(0.,uEdgeFade,1.-vWakeUv.y);
        normal=normalize(tbn*normalize(on+wn*nea*1.1*uWakeFade));
      #endif`)
    .replace('#include <lights_fragment_end>',`#include <lights_fragment_end>
      // UC: compress only the direct-sun specular peak so glints sparkle without clipping to flat white
      float pk=max(max(reflectedLight.directSpecular.r,reflectedLight.directSpecular.g),reflectedLight.directSpecular.b);
      if(pk>uSunHighlightKnee){ float ex=pk-uSunHighlightKnee; float cp=uSunHighlightKnee+ex/(1.0+uSunHighlightCompression*ex);
        reflectedLight.directSpecular*=cp/max(pk,0.00001); }`)
    .replace('#include <roughnessmap_fragment>',`#include <roughnessmap_fragment>\n roughnessFactor=mix(roughnessFactor,0.97,clamp(foamFactor*edgeAlpha,0.,1.));`)
    .replace('#include <metalnessmap_fragment>',`#include <metalnessmap_fragment>\n metalnessFactor=mix(metalnessFactor,0.0,clamp(foamFactor*edgeAlpha,0.,1.));`);
    mat.userData.shader=sh;
  };
  return {mat,uni};
}

const SHIP_LENGTH_WORLD=11;   // the world-unit scale a hull-length beat/game shares; seaway-wake's own MAX_DISTANCE stays local to that beat

// 2 Oct 2026, Simon: "the waves on the water surface over the whole plate switch to a different pattern at the
// transition [into noirmont-transit]... combined with the turn not being smooth makes it all appear very
// glitchy" — real cause: seaway-wake and noirmont-transit each run their own independent ocean/wake simulation
// (own WebGL context, own mount()), and each one used to measure its own `t` (fed to uTime, the bob/swell sine
// waves, Corbière's light phase, etc.) from ITS OWN mount-time performance.now() — "seconds since THIS beat
// mounted." Since beats mount in sequence, each awaiting its own texture loads first, noirmont-transit's own t0
// could land anywhere from under a second to several seconds after seaway-wake's, with no relationship between
// them — so the whole procedural wave field (not just the hull's wake trail) was at an essentially unrelated
// phase the instant the layers swapped, on top of (not the same bug as) the hull-rotation/wake-warmup snap
// fixed earlier the same day. PAGE_T0 is one shared epoch, captured once when this module is first evaluated
// (both beats import the same singleton ES module instance, so they share the exact same instant) — every beat
// that imports it and uses `(now-PAGE_T0)/1000` for its own `t` stays on one continuous page-global clock, so
// the SAME wave shape/phase appears at the same world position at the same real moment in both beats, not just
// a cosmetically similar one.
const PAGE_T0 = performance.now();

